"""Generates ELM327_Emulator/vehicles.h: recorded answers of real vehicles for the CAN mode.

    python tools/gen_vehicles.py PATH/TO/vehicle-profiles

The answers come from the test cases in PitLogger/vehicle-profiles (recorded by OBDb contributors,
CC BY-SA 4.0). For each vehicle, every manufacturer request (services 21/22) that answered in the
chosen model year is included, with the answers recorded in that year where there are any,
otherwise with those of other years. Standard OBD-II requests (01, 03, 09, ...) are not included:
the emulator answers them from its simulated drive, so values change over time.
"""
import json
import os
import sys

# name shown on the console, profile, model year, VIN (made up, WMI and model year code fit)
VEHICLES = [
    ("Hyundai i30 N 2021", "vehicles/hyundai/i30", 2021, "TMAH381EAMJ000001"),
    ("Toyota bZ4X 2022", "vehicles/toyota/bz4x", 2022, "JTMABABA0NA000001"),
]
MAX_ANSWERS = 12   # per request, cycled through on every request


def payloads(frames, extended):
    """ISO-TP messages of a recorded answer: [(can id, bytes)]."""
    partial, out = {}, []
    for line in frames:
        parts = line.split()
        can_id, data = int(parts[0], 16), bytes(int(b, 16) for b in parts[1:])
        if extended:
            data = data[1:]
        if not data:
            continue
        kind = data[0] >> 4
        if kind == 0:
            out.append((can_id, data[1:1 + (data[0] & 0x0F)]))
        elif kind == 1 and len(data) >= 2:
            partial[can_id] = (bytearray(data[2:]), ((data[0] & 0x0F) << 8) | data[1])
        elif kind == 2 and can_id in partial:
            buf, size = partial[can_id]
            buf += data[1:]
            if len(buf) >= size:
                out.append((can_id, bytes(buf[:size])))
                del partial[can_id]
    return out


def collect(root, profile_id, year):
    with open(os.path.join(root, "profiles", profile_id + ".json"), encoding="utf-8") as f:
        profile = json.load(f)
    with open(os.path.join(root, "tests", profile_id + ".json"), encoding="utf-8") as f:
        cases = json.load(f)["cases"]
    requests = []
    for req in profile["requests"]:
        if year not in req.get("answeredIn", []) or req["bus"] != "can11" or req.get("extendedAddress"):
            continue
        if req["request"][:2] not in ("21", "22"):
            continue
        mine = [c for c in cases if c["request"] == req["id"]]
        mine = [c for c in mine if c["year"] == year] or mine
        answers = []
        for c in mine:
            for can_id, data in payloads(c["frames"], False):
                if can_id == int(req["rx"], 16) and data and data[0] == int(req["request"][:2], 16) + 0x40 \
                        and data not in [a for _, a in answers]:
                    answers.append((can_id, data))
        if answers:
            requests.append((int(req["tx"], 16), int(req["rx"], 16), bytes.fromhex(req["request"]),
                             answers[:MAX_ANSWERS]))
    return requests


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = sys.argv[1]
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "ELM327_Emulator", "vehicles.h")
    lines = [
        "// Generated by tools/gen_vehicles.py - do not edit.",
        "// Recorded answers of real vehicles from PitLogger/vehicle-profiles (OBDb, CC BY-SA 4.0).",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct RecRequest {",
        "  uint16_t tx, rx;           // CAN IDs of request and answer",
        "  uint8_t  reqLen;",
        "  uint8_t  req[4];           // service + identifier",
        "  uint16_t first, count;     // answers in REC_ANSWERS",
        "};",
        "",
        "struct RecAnswer {",
        "  uint16_t offset, len;      // bytes in REC_DATA",
        "};",
        "",
        "struct RecVehicle {",
        "  const char       *name;",
        "  const char       *vin;",
        "  const RecRequest *requests;",
        "  uint16_t          requestCount;",
        "};",
        "",
    ]
    data, answers, vehicles = bytearray(), [], []
    for vi, (name, pid, year, vin) in enumerate(VEHICLES):
        reqs = collect(root, pid, year)
        lines.append(f"static const RecRequest REC_REQUESTS_{vi}[] = {{")
        for tx, rx, req, ans in reqs:
            first = len(answers)
            for _, payload in ans:
                answers.append((len(data), len(payload)))
                data += payload
            req_bytes = ", ".join(f"0x{b:02X}" for b in req)
            lines.append(f"  {{ 0x{tx:03X}, 0x{rx:03X}, {len(req)}, {{ {req_bytes} }}, {first}, {len(ans)} }},")
        lines.append("};")
        lines.append("")
        vehicles.append((name, vin, f"REC_REQUESTS_{vi}", len(reqs)))
        print(f"{name}: {len(reqs)} requests")
    lines.append("static const RecAnswer REC_ANSWERS[] = {")
    for i in range(0, len(answers), 6):
        lines.append("  " + " ".join(f"{{ {o}, {n} }}," for o, n in answers[i:i + 6]))
    lines.append("};")
    lines.append("")
    lines.append("static const uint8_t REC_DATA[] = {")
    for i in range(0, len(data), 16):
        lines.append("  " + " ".join(f"0x{b:02X}," for b in data[i:i + 16]))
    lines.append("};")
    lines.append("")
    lines.append("static const RecVehicle REC_VEHICLES[] = {")
    for name, vin, arr, n in vehicles:
        lines.append(f'  {{ "{name}", "{vin}", {arr}, {n} }},')
    lines.append("};")
    lines.append("static const uint8_t REC_VEHICLE_COUNT = sizeof(REC_VEHICLES) / sizeof(REC_VEHICLES[0]);")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(answers)} answers, {len(data)} bytes -> {out}")


if __name__ == "__main__":
    main()
